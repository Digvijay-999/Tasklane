"""Build the final artifacts: summary.md and manifest.json (pure functions).

Both are deterministic: no timestamps or timings in the content, so rerunning a job with the same
input and settings produces byte-identical files. (Creation times and per-call latencies are in
the database.)
"""

import re
import unicodedata
from typing import Any

from app.domain.costs import Pricing, cost_record

MANIFEST_SCHEMA = "tasklane.pdf_manifest/1"

STUB_NOTICE = (
    "> This summary was produced by the built-in stub provider, which extracts leading "
    "sentences and frequent terms. It is a placeholder, not an AI-generated summary."
)

LLM_NOTICE = (
    "> This summary was generated by a language model from the document's text. It can be "
    "inaccurate or incomplete, and it is shown as untrusted text."
)


def usage_section(summary: dict[str, Any], pricing: Pricing | None) -> dict[str, Any]:
    """Calls and tokens behind this summary (cached chunk summaries included), and the
    estimated cost, only when prices are configured and the provider reported the tokens."""
    prompt, completion = summary.get("prompt_tokens"), summary.get("completion_tokens")
    return {
        "provider_calls": summary["calls"],
        # Token counts only when the provider reports them; never estimated.
        "prompt_tokens": prompt,
        "completion_tokens": completion,
        "total_tokens": summary.get("total_tokens"),
        "estimated_cost": cost_record(pricing, prompt, completion),
    }


# Characters that can change how a line renders: emphasis, code, links, HTML, headings, tables.
# "&" too, or "&#x202e;" would render as the invisible character it encodes.
_MARKDOWN_SPECIAL = re.compile(r"([\\`*_\[\]<>#|~&])")


def escape_markdown(text: str) -> str:
    """Escape a user-supplied string (the display filename) so it renders as plain text."""
    return _MARKDOWN_SPECIAL.sub(r"\\\1", " ".join(text.split()))


def visible(text: str, keep: str = "") -> str:
    """Control and format characters (category C*, e.g. right-to-left overrides, zero-width
    spaces) written as visible \\uXXXX text, except those in `keep`."""
    return "".join(
        f"\\u{ord(char):04x}" if unicodedata.category(char)[0] == "C" and char not in keep else char
        for char in text
    )


def fenced(text: str) -> str:
    """Put text in a fenced code block it can't break out of, with invisible characters (other
    than line breaks and tabs) made visible."""
    text = visible(text, keep="\n\t")
    longest = max((len(run) for run in re.findall(r"~+", text)), default=0)
    fence = "~" * max(3, longest + 1)
    return f"{fence}\n{text}\n{fence}"


def build_summary_markdown(
    *, display_filename: str, extract: dict[str, Any], summary: dict[str, Any]
) -> str:
    lines = [
        f"# Summary of {escape_markdown(display_filename)}",
        "",
        f"{extract['pages']} pages, {extract['characters']} characters of text. "
        f"Summarized by `{summary['provider']}` / `{summary['model']}`.",
    ]
    lines += ["", STUB_NOTICE if summary["provider"] == "stub" else LLM_NOTICE]
    if extract.get("pages_without_text"):
        lines += [
            "",
            f"> {extract['pages_without_text']} of {extract['pages']} pages had no extractable "
            "text (for example scanned images) and are not covered.",
        ]
    # Summaries come from document text (with an LLM provider they could contain anything):
    # fenced, so they render as plain preformatted text, never links, images or HTML.
    lines += ["", "## Summary", "", fenced(summary["final"]), "", "## Sections"]
    for section in summary["sections"]:
        pages = (
            f"Page {section['page_start']}"
            if section["page_start"] == section["page_end"]
            else f"Pages {section['page_start']}-{section['page_end']}"
        )
        lines += ["", f"### {pages}", "", fenced(section["summary"])]
    return "\n".join(lines) + "\n"


def build_manifest(
    *,
    job_id: str,
    workflow_type: str,
    upload: dict[str, Any],
    validate: dict[str, Any],
    extract: dict[str, Any],
    chunking: dict[str, Any],
    summary: dict[str, Any],
    pricing: Pricing | None = None,
    artifacts: list[dict[str, Any]],
) -> dict[str, Any]:
    return {
        "schema": MANIFEST_SCHEMA,
        "job_id": job_id,
        "workflow": workflow_type,
        "input": {
            "upload_id": upload["upload_id"],
            "filename": upload["filename"],
            "sha256": upload["sha256"],
            "size_bytes": upload["size_bytes"],
            "pages": extract["pages"],
            "pages_with_text": extract["pages_with_text"],
            "pages_without_text": extract["pages_without_text"],
            "characters": extract["characters"],
            "owner_password_only": validate["owner_password_only"],
        },
        "chunking": chunking,
        "summary": {
            "provider": summary["provider"],
            "model": summary["model"],
            "chunk_summaries": len(summary["sections"]),
            "combine_rounds": summary["combine_rounds"],
        },
        "usage": usage_section(summary, pricing),
        # Secrets replaced before text was sent to a real provider: counts only, never values.
        # Null with the stub (nothing leaves the machine).
        "secret_scrubbing": summary.get("secret_scrubbing"),
        "artifacts": artifacts,
    }
